USE ROLE LUZ_ADMIN;
USE WAREHOUSE LUZ_TRANSFORM_WH;
USE DATABASE LUZSAUDE_DEMO;
USE SCHEMA GOV;

-- ---------- Tags ----------
CREATE TAG IF NOT EXISTS GOV.DATA_CLASS ALLOWED_VALUES 'PII', 'PHI', 'FINANCIAL', 'HR_SENSITIVE', 'PUBLIC' COMMENT = 'Data classification (RGPD / sigilo médico)';
CREATE TAG IF NOT EXISTS GOV.DATA_DOMAIN ALLOWED_VALUES 'Clínico', 'Financeiro', 'Pessoas', 'Cliente', 'Externo' COMMENT = 'Data product domain';
CREATE TAG IF NOT EXISTS GOV.DATA_OWNER COMMENT = 'Business owner of the data product';

-- ---------- Entitlements: which hospitals each role may see ----------
CREATE OR REPLACE TABLE GOV.HOSPITAL_ENTITLEMENTS (ROLE_NAME STRING, HOSPITAL_ID STRING) COMMENT = 'Row-level entitlements for hospital management roles';
INSERT INTO GOV.HOSPITAL_ENTITLEMENTS VALUES ('LUZ_DIRECAO_HOSPITAL', 'H01');  -- the demo hospital director runs HL Lisboa

-- ---------- Masking policies ----------
-- Diagnoses and clinical free text: clinical roles only.
CREATE OR REPLACE MASKING POLICY GOV.MASK_CLINICAL AS (V STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('LUZ_CLINICO') OR IS_ROLE_IN_SESSION('LUZ_ADMIN') THEN V
       ELSE '*** reservado (sigilo médico) ***' END
  COMMENT = 'Diagnoses and clinical notes visible only to clinical roles';

-- Patient and employee names: visible to clinical and admin roles; pseudonymised for everyone else.
CREATE OR REPLACE MASKING POLICY GOV.MASK_NAME AS (V STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('LUZ_CLINICO') OR IS_ROLE_IN_SESSION('LUZ_ADMIN') OR IS_ROLE_IN_SESSION('LUZ_APP') THEN V
       ELSE 'Pseudónimo ' || UPPER(LEFT(SHA2(V), 8)) END
  COMMENT = 'Names pseudonymised for non-clinical roles';

-- Birth dates: shifted to the 1st of January for non-clinical roles (keeps the age band).
CREATE OR REPLACE MASKING POLICY GOV.MASK_BIRTH_DATE AS (V DATE) RETURNS DATE ->
  CASE WHEN IS_ROLE_IN_SESSION('LUZ_CLINICO') OR IS_ROLE_IN_SESSION('LUZ_ADMIN') THEN V ELSE DATE_FROM_PARTS(YEAR(V), 1, 1) END;

-- HR sensitive scores (leave risk): HR and admin only.
CREATE OR REPLACE MASKING POLICY GOV.MASK_HR_SCORE AS (V FLOAT) RETURNS FLOAT ->
  CASE WHEN IS_ROLE_IN_SESSION('LUZ_ADMIN') THEN V ELSE NULL END
  COMMENT = 'Predicted leave risk visible only to HR (never used with gender, age or nationality)';

-- ---------- Row access: hospital directors see only their hospitals ----------
CREATE OR REPLACE ROW ACCESS POLICY GOV.RAP_HOSPITAL AS (HOSPITAL_ID STRING) RETURNS BOOLEAN ->
  NOT IS_ROLE_IN_SESSION('LUZ_DIRECAO_HOSPITAL') OR IS_ROLE_IN_SESSION('LUZ_ADMIN')
  OR EXISTS (SELECT 1 FROM GOV.HOSPITAL_ENTITLEMENTS e WHERE e.ROLE_NAME = 'LUZ_DIRECAO_HOSPITAL' AND e.HOSPITAL_ID = HOSPITAL_ID)
  COMMENT = 'Hospital management roles only see the hospitals they are entitled to';

-- ---------- Apply to the CORE layer ----------
ALTER DYNAMIC TABLE CORE.INPATIENT_EPISODE MODIFY COLUMN DIAGNOSIS SET MASKING POLICY GOV.MASK_CLINICAL;
ALTER DYNAMIC TABLE CORE.INPATIENT_EPISODE MODIFY COLUMN DIAGNOSIS_CODE SET MASKING POLICY GOV.MASK_CLINICAL;
ALTER DYNAMIC TABLE CORE.INPATIENT_EPISODE ADD ROW ACCESS POLICY GOV.RAP_HOSPITAL ON (HOSPITAL_ID);
ALTER DYNAMIC TABLE CORE.ER_EPISODE ADD ROW ACCESS POLICY GOV.RAP_HOSPITAL ON (HOSPITAL_ID);
ALTER DYNAMIC TABLE CORE.SURGERY ADD ROW ACCESS POLICY GOV.RAP_HOSPITAL ON (HOSPITAL_ID);
ALTER DYNAMIC TABLE CORE.INVOICE ADD ROW ACCESS POLICY GOV.RAP_HOSPITAL ON (HOSPITAL_ID);
ALTER DYNAMIC TABLE CORE.INVOICE MODIFY COLUMN RESPONSE_TEXT SET TAG GOV.DATA_CLASS = 'FINANCIAL';
ALTER DYNAMIC TABLE CORE.HOSPITAL_DAY_KPI ADD ROW ACCESS POLICY GOV.RAP_HOSPITAL ON (HOSPITAL_ID);
ALTER DYNAMIC TABLE CORE.DIM_PATIENT MODIFY COLUMN FULL_NAME SET MASKING POLICY GOV.MASK_NAME;
ALTER DYNAMIC TABLE CORE.DIM_PATIENT MODIFY COLUMN BIRTH_DATE SET MASKING POLICY GOV.MASK_BIRTH_DATE;
ALTER DYNAMIC TABLE CORE.PATIENT_360 MODIFY COLUMN FULL_NAME SET MASKING POLICY GOV.MASK_NAME;
ALTER DYNAMIC TABLE CORE.PATIENT_360 MODIFY COLUMN BIRTH_DATE SET MASKING POLICY GOV.MASK_BIRTH_DATE;
ALTER DYNAMIC TABLE CORE.PATIENT_360 MODIFY COLUMN PROFILE_SUMMARY SET MASKING POLICY GOV.MASK_CLINICAL;
ALTER DYNAMIC TABLE CORE.EMPLOYEE_360 MODIFY COLUMN LEAVE_RISK_SCORE SET MASKING POLICY GOV.MASK_HR_SCORE;
ALTER DYNAMIC TABLE CORE.EMPLOYEE_360 ADD ROW ACCESS POLICY GOV.RAP_HOSPITAL ON (HOSPITAL_ID);
ALTER TABLE RAW.CLINICAL_NOTES MODIFY COLUMN NOTE_TEXT SET MASKING POLICY GOV.MASK_CLINICAL;

-- Classification tags
ALTER DYNAMIC TABLE CORE.DIM_PATIENT MODIFY COLUMN FULL_NAME SET TAG GOV.DATA_CLASS = 'PII';
ALTER DYNAMIC TABLE CORE.DIM_PATIENT MODIFY COLUMN BIRTH_DATE SET TAG GOV.DATA_CLASS = 'PII';
