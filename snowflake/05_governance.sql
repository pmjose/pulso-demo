ALTER TABLE RAW.CLINICAL_NOTES MODIFY COLUMN NOTE_TEXT SET TAG GOV.DATA_CLASS = 'PHI';
ALTER DYNAMIC TABLE CORE.EMPLOYEE_360 MODIFY COLUMN LEAVE_RISK_SCORE SET TAG GOV.DATA_CLASS = 'HR_SENSITIVE';
ALTER DYNAMIC TABLE CORE.INPATIENT_EPISODE SET TAG GOV.DATA_DOMAIN = 'Clínico', GOV.DATA_OWNER = 'Direção Clínica';
ALTER DYNAMIC TABLE CORE.INVOICE SET TAG GOV.DATA_DOMAIN = 'Financeiro', GOV.DATA_OWNER = 'Direção Financeira';
ALTER DYNAMIC TABLE CORE.EMPLOYEE_360 SET TAG GOV.DATA_DOMAIN = 'Pessoas', GOV.DATA_OWNER = 'Direção de Recursos Humanos';
ALTER DYNAMIC TABLE CORE.PATIENT_360 SET TAG GOV.DATA_DOMAIN = 'Cliente', GOV.DATA_OWNER = 'Experiência do Cliente';

-- ---------- Learning Health: consented, pseudonymised research cohort ----------
-- Only patients who consented in MY LUZ; irreversible keys; dates shifted per patient.
CREATE OR REPLACE SECURE VIEW GOV.RESEARCH_INPATIENT_COHORT
  COMMENT = 'Learning Health cohort: consented patients only, pseudonymised ids, per-patient date shift'
AS
SELECT SHA2(e.PATIENT_ID || 'luz-research-salt') AS RESEARCH_PATIENT_KEY,
       p.AGE_BAND, p.SEX, p.REGION, e.SPECIALTY, e.DIAGNOSIS_CODE,
       DATEADD(day, MOD(ABS(HASH(e.PATIENT_ID, 'shift')), 61) - 30, e.ADMISSION_DATE) AS ADMISSION_DATE_SHIFTED,
       e.LOS_DAYS, e.READMITTED_30D
FROM CORE.INPATIENT_EPISODE e
JOIN CORE.DIM_PATIENT p ON p.PATIENT_ID = e.PATIENT_ID
WHERE p.CONSENT_RESEARCH;

