USE ROLE LUZ_ADMIN;
USE WAREHOUSE LUZ_TRANSFORM_WH;
USE DATABASE LUZSAUDE_DEMO;
USE SCHEMA OPS;

-- ---------- Alert log (what the portal's "Alertas e subscrições" page reads) ----------
CREATE OR REPLACE TABLE OPS.ALERT_LOG (
  ALERT_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()::TIMESTAMP_NTZ, ALERT_NAME STRING, SEVERITY STRING, SCOPE STRING, MESSAGE STRING, DETAILS VARIANT
);

-- ---------- Daily scoring: refresh every prediction table from the trained models ----------
CREATE OR REPLACE PROCEDURE OPS.REFRESH_PREDICTIONS()
  RETURNS STRING
  LANGUAGE SQL
  COMMENT = 'Re-scores tomorrow''s appointments, unsent invoices, recent discharges, ER demand and payer anomalies'
AS
$$
BEGIN
  CREATE OR REPLACE TABLE ML.ER_DEMAND_PREDICTIONS AS
  SELECT SERIES::STRING AS HOSPITAL_ID, TS::DATE AS FORECAST_DATE, ROUND(FORECAST) AS ER_VISITS_FORECAST,
         ROUND(LOWER_BOUND) AS LOWER_90, ROUND(UPPER_BOUND) AS UPPER_90, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS SCORED_AT
  FROM TABLE(ML.ER_DEMAND_FORECAST!FORECAST(INPUT_DATA => TABLE(ML.ER_DAILY_FUTURE), SERIES_COLNAME => 'SERIES', TIMESTAMP_COLNAME => 'TS',
                                             CONFIG_OBJECT => {'prediction_interval': 0.9}));

  CREATE OR REPLACE TABLE ML.REJECTION_PREDICTIONS AS
  SELECT INVOICE_ID, HOSPITAL_ID, PAYER, SPECIALTY, AMOUNT_EUR, NEEDS_PRIOR_AUTH, HAS_PRIOR_AUTH,
         ROUND(ML.REJECTION_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'PAYER_ID', PAYER_ID, 'EPISODE_TYPE', EPISODE_TYPE, 'SPECIALTY', SPECIALTY, 'IS_IMAGING', IS_IMAGING, 'NEEDS_PRIOR_AUTH', NEEDS_PRIOR_AUTH,
           'HAS_PRIOR_AUTH', HAS_PRIOR_AUTH, 'AMOUNT_EUR', AMOUNT_EUR::FLOAT, 'AFTER_PAYER_RULE_CHANGE', SERVICE_DATE >= '2026-11-01')):probability:"True"::FLOAT, 4) AS REJECTION_PROBABILITY
  FROM CORE.INVOICE WHERE STATUS = 'Por enviar';

  CREATE OR REPLACE TABLE ML.REJECTION_ANOMALIES AS
  SELECT SERIES::STRING AS PAYER, TS::DATE AS SERVICE_DATE, ROUND(Y, 2) AS REJECTION_PCT, ROUND(FORECAST, 2) AS EXPECTED_PCT,
         ROUND(UPPER_BOUND, 2) AS UPPER_BOUND, IS_ANOMALY, ROUND(PERCENTILE, 3) AS PERCENTILE
  FROM TABLE(ML.REJECTION_ANOMALY!DETECT_ANOMALIES(
    INPUT_DATA => TABLE(ML.REJECTION_RATE_RECENT), SERIES_COLNAME => 'SERIES', TIMESTAMP_COLNAME => 'TS', TARGET_COLNAME => 'REJECTION_PCT',
    CONFIG_OBJECT => {'prediction_interval': 0.99}));
  RETURN 'Predictions refreshed at ' || CURRENT_TIMESTAMP()::STRING;
END;
$$;

CREATE OR REPLACE TASK OPS.T_DAILY_SCORING
  WAREHOUSE = LUZ_ML_WH
  SCHEDULE = 'USING CRON 0 6 * * * Europe/Lisbon'
  COMMENT = 'Daily 06:00 Lisboa: refresh ML predictions before the morning briefing'
AS CALL OPS.REFRESH_PREDICTIONS();

-- ---------- Hourly: classify new payer responses with AI_CLASSIFY (incremental) ----------
CREATE OR REPLACE TASK OPS.T_CLASSIFY_PAYER_RESPONSES
  WAREHOUSE = LUZ_APP_WH
  SCHEDULE = '60 MINUTE'
  COMMENT = 'Hourly: classify rejection reasons for payer responses received since the last run'
AS
INSERT INTO AI.PAYER_REJECTION_REASONS
SELECT r.RESPONSE_ID, r.INVOICE_ID, r.PAYER_ID, r.RECEIVED_AT,
  AI_CLASSIFY(r.RESPONSE_TEXT,
    ['Autorização prévia em falta', 'Código de ato incompatível', 'Fora da cobertura', 'Falta de justificação clínica', 'Duplicação de ato'],
    {'task_description': 'Classifica o motivo de rejeição de uma fatura hospitalar pela seguradora'}):labels[0]::STRING,
  CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM RAW.PAYER_RESPONSES r
WHERE NOT EXISTS (SELECT 1 FROM AI.PAYER_REJECTION_REASONS x WHERE x.RESPONSE_ID = r.RESPONSE_ID)
  AND r.RECEIVED_AT >= DATEADD(day, -14, CURRENT_TIMESTAMP());

-- ---------- Alerts ----------
-- ER surge: the 7-day forecast exceeds the last 4 weeks' average by more than 10% (triggers the contingency plan).
CREATE OR REPLACE ALERT OPS.A_ER_SURGE
  WAREHOUSE = LUZ_APP_WH
  SCHEDULE = 'USING CRON 30 6 * * * Europe/Lisbon'
  COMMENT = 'Previsão de afluência à urgência > 10% acima da média das últimas 4 semanas'
  IF (EXISTS (
    SELECT 1 FROM ML.ER_DEMAND_PREDICTIONS p
    JOIN (SELECT HOSPITAL_ID, AVG(ER_VISITS) avg4w FROM CORE.HOSPITAL_DAY_KPI WHERE KPI_DATE >= DATEADD(day, -28, '2026-11-11'::DATE) GROUP BY 1) b USING (HOSPITAL_ID)
    WHERE p.ER_VISITS_FORECAST > 1.10 * b.avg4w))
  THEN
    INSERT INTO OPS.ALERT_LOG (ALERT_NAME, SEVERITY, SCOPE, MESSAGE, DETAILS)
    SELECT 'Pico de afluência à urgência', 'Alta', h.SHORT_NAME,
           'Previsão de ' || p.ER_VISITS_FORECAST || ' episódios em ' || TO_CHAR(p.FORECAST_DATE, 'DD/MM') || ' (média 4 semanas: ' || ROUND(b.avg4w) || '). Avaliar plano de contingência.',
           OBJECT_CONSTRUCT('forecast_date', p.FORECAST_DATE, 'forecast', p.ER_VISITS_FORECAST, 'avg_4w', ROUND(b.avg4w))
    FROM ML.ER_DEMAND_PREDICTIONS p
    JOIN (SELECT HOSPITAL_ID, AVG(ER_VISITS) avg4w FROM CORE.HOSPITAL_DAY_KPI WHERE KPI_DATE >= DATEADD(day, -28, '2026-11-11'::DATE) GROUP BY 1) b USING (HOSPITAL_ID)
    JOIN REF.HOSPITALS h USING (HOSPITAL_ID)
    WHERE p.ER_VISITS_FORECAST > 1.10 * b.avg4w;

-- Payer anomaly: the anomaly detector flagged a payer in the last 7 days.
CREATE OR REPLACE ALERT OPS.A_PAYER_REJECTION_ANOMALY
  WAREHOUSE = LUZ_APP_WH
  SCHEDULE = 'USING CRON 45 6 * * * Europe/Lisbon'
  COMMENT = 'Taxa de rejeição de uma entidade fora do intervalo esperado (deteção de anomalias)'
  IF (EXISTS (SELECT 1 FROM ML.REJECTION_ANOMALIES WHERE IS_ANOMALY AND REJECTION_PCT > EXPECTED_PCT AND SERVICE_DATE >= DATEADD(day, -7, '2026-11-11'::DATE)))
  THEN
    INSERT INTO OPS.ALERT_LOG (ALERT_NAME, SEVERITY, SCOPE, MESSAGE, DETAILS)
    SELECT 'Taxa de rejeição anómala', 'Alta', PAYER,
           PAYER || ': rejeição de ' || REPLACE(TO_CHAR(REJECTION_PCT, 'FM990.0'), '.', ',') || '% em ' || TO_CHAR(SERVICE_DATE, 'DD/MM') || ' (esperado ' || REPLACE(TO_CHAR(EXPECTED_PCT, 'FM990.0'), '.', ',') || '%).',
           OBJECT_CONSTRUCT('payer', PAYER, 'date', SERVICE_DATE, 'actual', REJECTION_PCT, 'expected', EXPECTED_PCT)
    FROM ML.REJECTION_ANOMALIES WHERE IS_ANOMALY AND REJECTION_PCT > EXPECTED_PCT AND SERVICE_DATE >= DATEADD(day, -7, '2026-11-11'::DATE);

-- Keep everything suspended until the demo needs it.
ALTER TASK OPS.T_DAILY_SCORING SUSPEND;
ALTER TASK OPS.T_CLASSIFY_PAYER_RESPONSES SUSPEND;
ALTER ALERT OPS.A_ER_SURGE SUSPEND;
ALTER ALERT OPS.A_PAYER_REJECTION_ANOMALY SUSPEND;

-- Seed the alert log once with what the alerts would raise today, so the portal has something to show.
INSERT INTO OPS.ALERT_LOG (ALERT_NAME, SEVERITY, SCOPE, MESSAGE, DETAILS)
SELECT 'Taxa de rejeição anómala', 'Alta', PAYER,
       PAYER || ': rejeição de ' || REPLACE(TO_CHAR(REJECTION_PCT, 'FM990.0'), '.', ',') || '% em ' || TO_CHAR(SERVICE_DATE, 'DD/MM') || ' (esperado ' || REPLACE(TO_CHAR(EXPECTED_PCT, 'FM990.0'), '.', ',') || '%).',
       OBJECT_CONSTRUCT('payer', PAYER, 'date', SERVICE_DATE, 'actual', REJECTION_PCT, 'expected', EXPECTED_PCT)
FROM ML.REJECTION_ANOMALIES WHERE IS_ANOMALY AND REJECTION_PCT > EXPECTED_PCT AND SERVICE_DATE >= DATEADD(day, -7, '2026-11-11'::DATE);

-- ---------- Data quality: Data Metric Functions on the landing tables ----------
-- Rerunnable: this block first detaches any metric functions attached by a previous run.
EXECUTE IMMEDIATE $$
DECLARE c CURSOR FOR SELECT REF_ENTITY_NAME t, METRIC_DATABASE_NAME || '.' || METRIC_SCHEMA_NAME || '.' || METRIC_NAME f, REF_ARGUMENTS a
  FROM TABLE(LUZSAUDE_DEMO.INFORMATION_SCHEMA.DATA_METRIC_FUNCTION_REFERENCES(REF_ENTITY_NAME => 'LUZSAUDE_DEMO.RAW.BILLING_INVOICES', REF_ENTITY_DOMAIN => 'TABLE'))
  UNION ALL SELECT REF_ENTITY_NAME, METRIC_DATABASE_NAME || '.' || METRIC_SCHEMA_NAME || '.' || METRIC_NAME, REF_ARGUMENTS
  FROM TABLE(LUZSAUDE_DEMO.INFORMATION_SCHEMA.DATA_METRIC_FUNCTION_REFERENCES(REF_ENTITY_NAME => 'LUZSAUDE_DEMO.RAW.HIS_ER_ENCOUNTER_FHIR', REF_ENTITY_DOMAIN => 'TABLE'))
  UNION ALL SELECT REF_ENTITY_NAME, METRIC_DATABASE_NAME || '.' || METRIC_SCHEMA_NAME || '.' || METRIC_NAME, REF_ARGUMENTS
  FROM TABLE(LUZSAUDE_DEMO.INFORMATION_SCHEMA.DATA_METRIC_FUNCTION_REFERENCES(REF_ENTITY_NAME => 'LUZSAUDE_DEMO.RAW.HIS_APPOINTMENTS', REF_ENTITY_DOMAIN => 'TABLE'));
BEGIN
  FOR r IN c DO
    EXECUTE IMMEDIATE 'ALTER TABLE LUZSAUDE_DEMO.RAW.' || r.t || ' DROP DATA METRIC FUNCTION ' || r.f || ' ON (' || PARSE_JSON(r.a)[0]:name::STRING || ')';
  END FOR;
END;
$$;
ALTER TABLE RAW.HIS_ER_ENCOUNTER_FHIR SET DATA_METRIC_SCHEDULE = 'USING CRON 0 * * * * Europe/Lisbon';
ALTER TABLE RAW.BILLING_INVOICES SET DATA_METRIC_SCHEDULE = 'USING CRON 0 * * * * Europe/Lisbon';
ALTER TABLE RAW.HIS_APPOINTMENTS SET DATA_METRIC_SCHEDULE = 'USING CRON 0 * * * * Europe/Lisbon';

ALTER TABLE RAW.HIS_ER_ENCOUNTER_FHIR ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT ON (RESOURCE_ID);
ALTER TABLE RAW.BILLING_INVOICES ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (PAYER_ID);
ALTER TABLE RAW.BILLING_INVOICES ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT ON (INVOICE_ID);
ALTER TABLE RAW.HIS_APPOINTMENTS ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (PATIENT_ID);

-- Custom check: invoices with a negative or zero amount must never reach a payer.
CREATE OR REPLACE DATA METRIC FUNCTION OPS.INVALID_AMOUNT_COUNT(T TABLE(AMOUNT NUMBER(12,2)))
  RETURNS NUMBER
  COMMENT = 'Invoices with zero or negative amount'
AS 'SELECT COUNT_IF(AMOUNT <= 0) FROM T';
ALTER TABLE RAW.BILLING_INVOICES ADD DATA METRIC FUNCTION OPS.INVALID_AMOUNT_COUNT ON (AMOUNT_EUR);

-- Freshness is tracked by Dynamic Table target lag and the Observabilidade page; DMFs cannot use CURRENT_TIMESTAMP.

GRANT USAGE ON SCHEMA OPS TO ROLE LUZ_APP;
GRANT SELECT ON TABLE OPS.ALERT_LOG TO ROLE LUZ_APP;
