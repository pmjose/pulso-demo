USE ROLE LUZ_ADMIN;
USE WAREHOUSE LUZ_ML_WH;
USE DATABASE LUZSAUDE_DEMO;
USE SCHEMA ML;

-- ======================= 1. ER demand forecast (multi-series, exogenous) =======================
CREATE OR REPLACE VIEW ML.ER_DAILY_TRAIN AS
SELECT TO_VARIANT(k.HOSPITAL_ID) AS SERIES, k.KPI_DATE::TIMESTAMP_NTZ AS TS, k.ER_VISITS::FLOAT AS ER_VISITS,
       w.TEMP_MIN_C, COALESCE(ww.RESPIRATORY_VIRUS_INDEX, 50) AS RESP_INDEX, c.WEEKDAY::STRING AS WEEKDAY, c.IS_HOLIDAY::STRING AS IS_HOLIDAY
FROM CORE.HOSPITAL_DAY_KPI k
JOIN REF.HOSPITAL_DISTRICT hd ON hd.HOSPITAL_ID = k.HOSPITAL_ID
JOIN REF.DISTRICTS d ON d.DISTRICT = hd.DISTRICT
JOIN REF.CALENDAR c ON c.CAL_DATE = k.KPI_DATE
LEFT JOIN EXT.WEATHER_DAILY w ON w.DISTRICT = hd.DISTRICT AND w.OBS_DATE = k.KPI_DATE
LEFT JOIN EXT.WASTEWATER_WEEKLY ww ON ww.REGION = d.REGION AND ww.WEEK_START = DATE_TRUNC('week', DATEADD(day, -9, k.KPI_DATE));

-- Future exogenous values for 12-18 Nov 2026 (IPMA forecast, wastewater known 9 days ahead).
CREATE OR REPLACE VIEW ML.ER_DAILY_FUTURE AS
SELECT TO_VARIANT(h.HOSPITAL_ID) AS SERIES, c.CAL_DATE::TIMESTAMP_NTZ AS TS,
       w.TEMP_MIN_C, COALESCE(ww.RESPIRATORY_VIRUS_INDEX, 50) AS RESP_INDEX, c.WEEKDAY::STRING AS WEEKDAY, c.IS_HOLIDAY::STRING AS IS_HOLIDAY
FROM REF.HOSPITALS h
JOIN REF.HOSPITAL_DISTRICT hd ON hd.HOSPITAL_ID = h.HOSPITAL_ID
JOIN REF.DISTRICTS d ON d.DISTRICT = hd.DISTRICT
JOIN REF.CALENDAR c ON c.CAL_DATE BETWEEN '2026-11-12' AND '2026-11-18'
LEFT JOIN EXT.WEATHER_DAILY w ON w.DISTRICT = hd.DISTRICT AND w.OBS_DATE = c.CAL_DATE
LEFT JOIN EXT.WASTEWATER_WEEKLY ww ON ww.REGION = d.REGION AND ww.WEEK_START = DATE_TRUNC('week', DATEADD(day, -9, c.CAL_DATE));

CREATE OR REPLACE SNOWFLAKE.ML.FORECAST ML.ER_DEMAND_FORECAST(
  INPUT_DATA => TABLE(ML.ER_DAILY_TRAIN),
  SERIES_COLNAME => 'SERIES', TIMESTAMP_COLNAME => 'TS', TARGET_COLNAME => 'ER_VISITS'
) COMMENT = 'Afluência à urgência por hospital, 7 dias, com temperatura mínima (IPMA) e vírus respiratórios nas águas residuais (INSA)';

CREATE OR REPLACE TABLE ML.ER_DEMAND_PREDICTIONS AS
SELECT SERIES::STRING AS HOSPITAL_ID, TS::DATE AS FORECAST_DATE, ROUND(FORECAST) AS ER_VISITS_FORECAST,
       ROUND(LOWER_BOUND) AS LOWER_90, ROUND(UPPER_BOUND) AS UPPER_90, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS SCORED_AT
FROM TABLE(ML.ER_DEMAND_FORECAST!FORECAST(INPUT_DATA => TABLE(ML.ER_DAILY_FUTURE), SERIES_COLNAME => 'SERIES', TIMESTAMP_COLNAME => 'TS',
  CONFIG_OBJECT => {'prediction_interval': 0.9}));

-- ======================= 2. Revenue forecast to year end =======================
-- Month and weekday are exogenous features, so one year of history is enough to learn
-- that November and December are seasonally weaker.
CREATE OR REPLACE VIEW ML.REVENUE_DAILY_TRAIN AS
SELECT i.SERVICE_DATE::TIMESTAMP_NTZ AS TS, SUM(i.AMOUNT_EUR)::FLOAT / 1e6 AS REVENUE_MEUR,
       ANY_VALUE(c.MONTH_LABEL) AS MONTH_LABEL, ANY_VALUE(c.WEEKDAY::STRING) AS WEEKDAY, ANY_VALUE(c.IS_HOLIDAY::STRING) AS IS_HOLIDAY
FROM CORE.INVOICE i JOIN REF.CALENDAR c ON c.CAL_DATE = i.SERVICE_DATE
WHERE i.SERVICE_DATE BETWEEN '2025-11-12' AND '2026-11-11' GROUP BY 1;

CREATE OR REPLACE VIEW ML.REVENUE_DAILY_FUTURE AS
SELECT CAL_DATE::TIMESTAMP_NTZ AS TS, MONTH_LABEL, WEEKDAY::STRING AS WEEKDAY, IS_HOLIDAY::STRING AS IS_HOLIDAY
FROM REF.CALENDAR WHERE CAL_DATE BETWEEN '2026-11-12' AND '2026-12-31';

CREATE OR REPLACE SNOWFLAKE.ML.FORECAST ML.REVENUE_FORECAST(
  INPUT_DATA => TABLE(ML.REVENUE_DAILY_TRAIN), TIMESTAMP_COLNAME => 'TS', TARGET_COLNAME => 'REVENUE_MEUR'
) COMMENT = 'Previsão de fecho: receita diária do grupo até 31/12/2026 (sazonalidade mensal como variável exógena)';

CREATE OR REPLACE TABLE ML.REVENUE_PREDICTIONS AS
SELECT TS::DATE AS FORECAST_DATE, FORECAST AS REVENUE_MEUR_FORECAST, LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.REVENUE_FORECAST!FORECAST(INPUT_DATA => TABLE(ML.REVENUE_DAILY_FUTURE), TIMESTAMP_COLNAME => 'TS'));

-- 2026 close = actuals to date + forecast for the rest of the year.
CREATE OR REPLACE VIEW ML.REVENUE_CLOSE_2026 AS
SELECT (SELECT SUM(AMOUNT_EUR) / 1e6 FROM CORE.INVOICE WHERE SERVICE_DATE BETWEEN '2026-01-01' AND '2026-11-11') AS ACTUAL_TO_DATE_MEUR,
       (SELECT SUM(REVENUE_MEUR_FORECAST) FROM ML.REVENUE_PREDICTIONS) AS FORECAST_REST_OF_YEAR_MEUR,
       ACTUAL_TO_DATE_MEUR + FORECAST_REST_OF_YEAR_MEUR AS FORECAST_CLOSE_2026_MEUR,
       868 AS BUDGET_2026_MEUR;

-- ======================= 3. No-show classification =======================
CREATE OR REPLACE TABLE ML.NOSHOW_FEATURES AS
SELECT a.APPOINTMENT_ID, a.APPOINTMENT_DATE, a.STATUS, a.NO_SHOW,
       a.LEAD_DAYS, a.IS_FIRST_VISIT, a.CONFIRMED_IN_APP, a.DISTANCE_KM, a.RAIN_FORECAST, a.APPOINTMENT_HOUR, a.IS_TELECONSULT,
       a.SPECIALTY, a.UNIT_TYPE, a.BOOKING_CHANNEL, a.PAYER_ID,
       COUNT_IF(a.NO_SHOW) OVER (PARTITION BY a.PATIENT_ID ORDER BY a.APPOINTMENT_TS ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS PRIOR_NO_SHOWS
FROM CORE.APPOINTMENT a;

CREATE OR REPLACE VIEW ML.NOSHOW_TRAIN AS
SELECT NO_SHOW, LEAD_DAYS, IS_FIRST_VISIT, CONFIRMED_IN_APP, DISTANCE_KM, RAIN_FORECAST, APPOINTMENT_HOUR, IS_TELECONSULT,
       SPECIALTY, UNIT_TYPE, BOOKING_CHANNEL, PAYER_ID, PRIOR_NO_SHOWS
FROM ML.NOSHOW_FEATURES WHERE STATUS <> 'Marcada' AND MOD(ABS(HASH(APPOINTMENT_ID)), 12) = 0;   -- ~300k-row sample

CREATE OR REPLACE SNOWFLAKE.ML.CLASSIFICATION ML.NOSHOW_MODEL(
  INPUT_DATA => TABLE(ML.NOSHOW_TRAIN), TARGET_COLNAME => 'NO_SHOW', CONFIG_OBJECT => {'evaluate': TRUE}
) COMMENT = 'Faltas a consultas: probabilidade de no-show para lembretes e overbooking';

CREATE OR REPLACE TABLE ML.NOSHOW_PREDICTIONS AS
SELECT f.APPOINTMENT_ID, f.APPOINTMENT_DATE, f.SPECIALTY, f.LEAD_DAYS, f.CONFIRMED_IN_APP, f.PRIOR_NO_SHOWS,
       ROUND(p.PRED:probability:"True"::FLOAT, 4) AS NO_SHOW_PROBABILITY
FROM (SELECT f.*, ML.NOSHOW_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
         'LEAD_DAYS', LEAD_DAYS, 'IS_FIRST_VISIT', IS_FIRST_VISIT, 'CONFIRMED_IN_APP', CONFIRMED_IN_APP, 'DISTANCE_KM', DISTANCE_KM,
         'RAIN_FORECAST', RAIN_FORECAST, 'APPOINTMENT_HOUR', APPOINTMENT_HOUR, 'IS_TELECONSULT', IS_TELECONSULT, 'SPECIALTY', SPECIALTY,
         'UNIT_TYPE', UNIT_TYPE, 'BOOKING_CHANNEL', BOOKING_CHANNEL, 'PAYER_ID', PAYER_ID, 'PRIOR_NO_SHOWS', PRIOR_NO_SHOWS)) AS PRED
      FROM ML.NOSHOW_FEATURES f WHERE f.APPOINTMENT_DATE = '2026-11-13') p
JOIN ML.NOSHOW_FEATURES f USING (APPOINTMENT_ID);

-- ======================= 4. Payer rejection classification =======================
CREATE OR REPLACE VIEW ML.REJECTION_TRAIN AS
SELECT IS_REJECTED, PAYER_ID, EPISODE_TYPE, SPECIALTY, IS_IMAGING, NEEDS_PRIOR_AUTH, HAS_PRIOR_AUTH, AMOUNT_EUR::FLOAT AS AMOUNT_EUR,
       (SERVICE_DATE >= '2026-11-01') AS AFTER_PAYER_RULE_CHANGE
FROM CORE.INVOICE WHERE STATUS <> 'Por enviar' AND MOD(ABS(HASH(INVOICE_ID)), 14) = 0;

CREATE OR REPLACE SNOWFLAKE.ML.CLASSIFICATION ML.REJECTION_MODEL(
  INPUT_DATA => TABLE(ML.REJECTION_TRAIN), TARGET_COLNAME => 'IS_REJECTED', CONFIG_OBJECT => {'evaluate': TRUE}
) COMMENT = 'Risco de rejeição (glosa) antes do envio à entidade financiadora';

CREATE OR REPLACE TABLE ML.REJECTION_PREDICTIONS AS
SELECT INVOICE_ID, HOSPITAL_ID, PAYER, SPECIALTY, AMOUNT_EUR, NEEDS_PRIOR_AUTH, HAS_PRIOR_AUTH,
       ROUND(ML.REJECTION_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
         'PAYER_ID', PAYER_ID, 'EPISODE_TYPE', EPISODE_TYPE, 'SPECIALTY', SPECIALTY, 'IS_IMAGING', IS_IMAGING, 'NEEDS_PRIOR_AUTH', NEEDS_PRIOR_AUTH,
         'HAS_PRIOR_AUTH', HAS_PRIOR_AUTH, 'AMOUNT_EUR', AMOUNT_EUR::FLOAT, 'AFTER_PAYER_RULE_CHANGE', SERVICE_DATE >= '2026-11-01')):probability:"True"::FLOAT, 4) AS REJECTION_PROBABILITY
FROM CORE.INVOICE WHERE STATUS = 'Por enviar';

-- ======================= 5. 30-day readmission classification =======================
CREATE OR REPLACE TABLE ML.READMISSION_FEATURES AS
SELECT e.EPISODE_ID, e.PATIENT_ID, e.HOSPITAL_ID, e.DISCHARGE_DATE, e.READMITTED_30D,
       p.AGE, p.SEX, p.CHARLSON_INDEX, e.SPECIALTY, e.DIAGNOSIS_CODE, e.LOS_DAYS, e.DISPOSITION, e.DISCHARGED_BEFORE_NOON,
       COUNT(*) OVER (PARTITION BY e.PATIENT_ID ORDER BY e.ADMITTED_AT ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS PRIOR_ADMISSIONS
FROM CORE.INPATIENT_EPISODE e JOIN CORE.DIM_PATIENT p USING (PATIENT_ID)
WHERE NOT e.IS_ACTIVE;

CREATE OR REPLACE VIEW ML.READMISSION_TRAIN AS
SELECT READMITTED_30D, AGE, SEX, CHARLSON_INDEX, SPECIALTY, DIAGNOSIS_CODE, LOS_DAYS, DISPOSITION, DISCHARGED_BEFORE_NOON, PRIOR_ADMISSIONS
FROM ML.READMISSION_FEATURES WHERE DISCHARGE_DATE < '2026-10-12';   -- only episodes whose 30-day window is complete

CREATE OR REPLACE SNOWFLAKE.ML.CLASSIFICATION ML.READMISSION_MODEL(
  INPUT_DATA => TABLE(ML.READMISSION_TRAIN), TARGET_COLNAME => 'READMITTED_30D', CONFIG_OBJECT => {'evaluate': TRUE}
) COMMENT = 'Readmissão a 30 dias: prioriza o seguimento pós-alta';

CREATE OR REPLACE TABLE ML.READMISSION_PREDICTIONS AS
SELECT EPISODE_ID, PATIENT_ID, HOSPITAL_ID, DISCHARGE_DATE, SPECIALTY, AGE, CHARLSON_INDEX, PRIOR_ADMISSIONS,
       ROUND(ML.READMISSION_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
         'AGE', AGE, 'SEX', SEX, 'CHARLSON_INDEX', CHARLSON_INDEX, 'SPECIALTY', SPECIALTY, 'DIAGNOSIS_CODE', DIAGNOSIS_CODE, 'LOS_DAYS', LOS_DAYS,
         'DISPOSITION', DISPOSITION, 'DISCHARGED_BEFORE_NOON', DISCHARGED_BEFORE_NOON, 'PRIOR_ADMISSIONS', PRIOR_ADMISSIONS)):probability:"True"::FLOAT, 4) AS READMISSION_PROBABILITY
FROM ML.READMISSION_FEATURES WHERE DISCHARGE_DATE >= '2026-11-05';

-- ======================= 6. Anomaly detection on payer rejection rates =======================
CREATE OR REPLACE VIEW ML.REJECTION_RATE_DAILY AS
SELECT TO_VARIANT(PAYER) AS SERIES, SERVICE_DATE::TIMESTAMP_NTZ AS TS, (100 * COUNT_IF(IS_REJECTED) / COUNT(*))::FLOAT AS REJECTION_PCT
FROM CORE.INVOICE WHERE STATUS <> 'Por enviar' AND PAYER <> 'Particulares' AND SERVICE_DATE >= '2026-03-01' AND DAYOFWEEKISO(SERVICE_DATE) <= 5  -- weekdays: weekend volumes are too small
GROUP BY 1, 2;

CREATE OR REPLACE VIEW ML.REJECTION_RATE_TRAIN AS SELECT * FROM ML.REJECTION_RATE_DAILY WHERE TS < '2026-10-15';
CREATE OR REPLACE VIEW ML.REJECTION_RATE_RECENT AS SELECT * FROM ML.REJECTION_RATE_DAILY WHERE TS >= '2026-10-15';

CREATE OR REPLACE SNOWFLAKE.ML.ANOMALY_DETECTION ML.REJECTION_ANOMALY(
  INPUT_DATA => TABLE(ML.REJECTION_RATE_TRAIN), SERIES_COLNAME => 'SERIES', TIMESTAMP_COLNAME => 'TS', TARGET_COLNAME => 'REJECTION_PCT', LABEL_COLNAME => ''
) COMMENT = 'Anomalias de faturação: taxa diária de rejeição por entidade financiadora';

CREATE OR REPLACE TABLE ML.REJECTION_ANOMALIES AS
SELECT SERIES::STRING AS PAYER, TS::DATE AS SERVICE_DATE, ROUND(Y, 2) AS REJECTION_PCT, ROUND(FORECAST, 2) AS EXPECTED_PCT,
       ROUND(UPPER_BOUND, 2) AS UPPER_BOUND, IS_ANOMALY, ROUND(PERCENTILE, 3) AS PERCENTILE
FROM TABLE(ML.REJECTION_ANOMALY!DETECT_ANOMALIES(
  INPUT_DATA => TABLE(ML.REJECTION_RATE_RECENT), SERIES_COLNAME => 'SERIES', TIMESTAMP_COLNAME => 'TS', TARGET_COLNAME => 'REJECTION_PCT',
  CONFIG_OBJECT => {'prediction_interval': 0.99}));

-- ======================= 7. Snowpark ML + Model Registry: surgery duration (XGBoost) =======================
CREATE OR REPLACE PROCEDURE ML.TRAIN_SURGERY_DURATION()
  RETURNS VARIANT
  LANGUAGE PYTHON
  RUNTIME_VERSION = '3.11'
  PACKAGES = ('snowflake-snowpark-python', 'snowflake-ml-python', 'xgboost', 'scikit-learn', 'pandas')
  HANDLER = 'run'
  COMMENT = 'Trains the surgery-duration model (P50) with XGBoost and logs it to the Model Registry'
AS $$
from snowflake.ml.modeling.xgboost import XGBRegressor
from snowflake.ml.modeling.preprocessing import OneHotEncoder
from snowflake.ml.registry import Registry
import snowflake.snowpark.functions as F

def run(session):
    df = session.table("LUZSAUDE_DEMO.CORE.SURGERY").filter(F.col("CANCELLED_SAME_DAY") == False).select(
        "SPECIALTY", "PROCEDURE_NAME", "SURGEON", "ASA", "AGE", "IS_ROBOTIC", "SURGEON_ESTIMATE_MIN", "ACTUAL_DURATION_MIN")
    df = df.with_column("IS_ROBOTIC", F.col("IS_ROBOTIC").cast("int"))
    cats = ["SPECIALTY", "PROCEDURE_NAME", "SURGEON"]
    enc = OneHotEncoder(input_cols=cats, output_cols=[c + "_OH" for c in cats], drop_input_cols=True, handle_unknown="ignore")
    df = enc.fit(df).transform(df)
    train, test = df.random_split([0.8, 0.2], seed=42)
    features = [c for c in df.columns if c != "ACTUAL_DURATION_MIN"]
    model = XGBRegressor(input_cols=features, label_cols=["ACTUAL_DURATION_MIN"], output_cols=["PREDICTED_MIN"], n_estimators=300, max_depth=6, learning_rate=0.08)
    model.fit(train)
    scored = model.predict(test)
    mae = scored.select(F.avg(F.abs(F.col("PREDICTED_MIN") - F.col("ACTUAL_DURATION_MIN")))).collect()[0][0]
    base = scored.select(F.avg(F.abs(F.col("SURGEON_ESTIMATE_MIN") - F.col("ACTUAL_DURATION_MIN")))).collect()[0][0]
    reg = Registry(session=session, database_name="LUZSAUDE_DEMO", schema_name="ML")
    mv = reg.log_model(model, model_name="SURGERY_DURATION", version_name="V" + str(abs(hash(str(mae))) % 100000),
                       comment="Duração cirúrgica (P50) · XGBoost · Snowpark ML",
                       metrics={"mae_minutes": float(mae), "surgeon_estimate_mae_minutes": float(base)})
    return {"model": "SURGERY_DURATION", "version": mv.version_name, "mae_minutes": round(float(mae), 1), "surgeon_estimate_mae_minutes": round(float(base), 1)}
$$;

CALL ML.TRAIN_SURGERY_DURATION();

-- ======================= Model catalogue view: what is deployed and how it performs =======================
CREATE OR REPLACE VIEW ML.MODEL_INVENTORY AS
SELECT MODEL_ID, NAME, USE_CASE, ALGORITHM, STATUS, METRIC_NAME, METRIC_VALUE, PREDICTIONS_PER_DAY,
       CASE NAME WHEN 'Afluência à urgência' THEN 'ML.ER_DEMAND_FORECAST' WHEN 'Faltas a consultas' THEN 'ML.NOSHOW_MODEL'
                 WHEN 'Risco de rejeição' THEN 'ML.REJECTION_MODEL' WHEN 'Readmissão a 30 dias' THEN 'ML.READMISSION_MODEL'
                 WHEN 'Duração cirúrgica' THEN 'ML.SURGERY_DURATION (Model Registry)' WHEN 'Anomalias de faturação' THEN 'ML.REJECTION_ANOMALY' END AS SNOWFLAKE_OBJECT
FROM REF.MODEL_CATALOG;

