-- ==========================================================================================
-- 04_core_dynamic_tables.sql  ·  CONFORMED + CORE layer as Dynamic Tables
-- Parses HL7/FHIR, pairs admissions with discharges, derives occupancy, and builds the
-- 360° models and daily KPI tables the semantic views read. Lineage is automatic.
-- ==========================================================================================
USE ROLE LUZ_ADMIN;
USE WAREHOUSE LUZ_TRANSFORM_WH;
USE DATABASE LUZSAUDE_DEMO;
USE SCHEMA CORE;

-- ---------- Dimensions ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.DIM_PATIENT TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Patient master (MPI): one row per patient'
AS
SELECT p.PATIENT_ID, p.PROFILE_ID, p.FULL_NAME, p.SEX, p.BIRTH_DATE,
       FLOOR(MONTHS_BETWEEN('2026-11-12'::DATE, p.BIRTH_DATE) / 12) AS AGE,
       CASE WHEN FLOOR(MONTHS_BETWEEN('2026-11-12'::DATE, p.BIRTH_DATE) / 12) < 18 THEN '0-17' WHEN FLOOR(MONTHS_BETWEEN('2026-11-12'::DATE, p.BIRTH_DATE) / 12) < 45 THEN '18-44'
            WHEN FLOOR(MONTHS_BETWEEN('2026-11-12'::DATE, p.BIRTH_DATE) / 12) < 65 THEN '45-64' WHEN FLOOR(MONTHS_BETWEEN('2026-11-12'::DATE, p.BIRTH_DATE) / 12) < 80 THEN '65-79' ELSE '80+' END AS AGE_BAND,
       p.DISTRICT, d.REGION, p.MAIN_PAYER_ID, py.SHORT_NAME AS MAIN_PAYER, p.IS_PRIME, p.MYLUZ_USER, p.CHARLSON_INDEX,
       p.CONSENT_RESEARCH, p.CONSENT_HEALTH_COMMS, p.CREATED_AT AS CUSTOMER_SINCE
FROM RAW.HIS_PATIENTS p
LEFT JOIN REF.DISTRICTS d ON d.DISTRICT = p.DISTRICT
LEFT JOIN REF.PAYERS py ON py.PAYER_ID = p.MAIN_PAYER_ID;

CREATE OR REPLACE DYNAMIC TABLE CORE.DIM_EMPLOYEE TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Employees flattened from SuccessFactors OData payloads'
AS
SELECT EMPLOYEE_ID, PAYLOAD:profileId::STRING AS PROFILE_ID, PAYLOAD:displayName::STRING AS FULL_NAME, PAYLOAD:gender::STRING AS SEX,
       PAYLOAD:jobFamily::STRING AS ROLE_NAME, PAYLOAD:department::STRING AS SERVICE, PAYLOAD:location::STRING AS HOSPITAL_ID,
       PAYLOAD:hireDate::DATE AS HIRE_DATE, DATEDIFF(year, PAYLOAD:hireDate::DATE, '2026-11-12'::DATE) AS YEARS_OF_SERVICE,
       PAYLOAD:contractType::STRING AS CONTRACT_TYPE, PAYLOAD:performanceRating::FLOAT AS PERFORMANCE_RATING,
       PAYLOAD:nightShifts::BOOLEAN AS WORKS_NIGHTS, PAYLOAD:leaveRiskScore::FLOAT AS LEAVE_RISK_SCORE
FROM RAW.SF_EMPLOYEES;

-- ---------- Urgência ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.ER_EPISODE TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Emergency episodes parsed from FHIR R4 Encounter resources'
AS
SELECT RESOURCE:id::STRING AS ER_EPISODE_ID,
       REPLACE(RESOURCE:serviceProvider:reference::STRING, 'Organization/', '') AS HOSPITAL_ID,
       REPLACE(RESOURCE:subject:reference::STRING, 'Patient/', '') AS PATIENT_ID,
       TO_TIMESTAMP_NTZ(RESOURCE:period:start::STRING) AS ARRIVED_AT,
       TO_TIMESTAMP_NTZ(RESOURCE:period:end::STRING) AS LEFT_AT,
       TO_DATE(TO_TIMESTAMP_NTZ(RESOURCE:period:start::STRING)) AS ARRIVAL_DATE,
       HOUR(TO_TIMESTAMP_NTZ(RESOURCE:period:start::STRING)) AS ARRIVAL_HOUR,
       RESOURCE:priority:coding[0]:code::STRING AS TRIAGE_LEVEL,
       DECODE(RESOURCE:priority:coding[0]:code::STRING, 'Vermelho', 0, 'Laranja', 10, 'Amarelo', 60, 'Verde', 120, 240) AS TRIAGE_TARGET_MIN,
       RESOURCE:extension[0]:valueInteger::INT AS WAIT_FIRST_PHYSICIAN_MIN,
       RESOURCE:reasonCode[0]:text::STRING AS REASON_GROUP,
       RESOURCE:hospitalization:dischargeDisposition:text::STRING = 'Internamento' AS ADMITTED
FROM RAW.HIS_ER_ENCOUNTER_FHIR;

-- ---------- Internamento: admissions paired with discharges, readmission within 30 days ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.INPATIENT_EPISODE TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Inpatient episodes from HL7 ADT A01/A03, with length of stay and 30-day readmission flag'
AS
WITH adm AS (
  SELECT MSG:PV1:"19"::STRING AS EPISODE_ID, MSG:PID:"3"::STRING AS PATIENT_ID, MSG:PV1:"3":"4"::STRING AS HOSPITAL_ID,
         MSG:PV1:"10"::STRING AS SPECIALTY, MSG:DG1:"3":"1"::STRING AS DIAGNOSIS_CODE, MSG:DG1:"3":"2"::STRING AS DIAGNOSIS,
         TO_TIMESTAMP_NTZ(MSG:PV1:"44"::STRING, 'YYYYMMDDHH24MISS') AS ADMITTED_AT
  FROM RAW.HIS_ADT_HL7 WHERE MSG_TYPE = 'ADT^A01'),
dis AS (
  SELECT MSG:PV1:"19"::STRING AS EPISODE_ID, TO_TIMESTAMP_NTZ(MSG:PV1:"45"::STRING, 'YYYYMMDDHH24MISS') AS DISCHARGED_AT, MSG:PV1:"36"::STRING AS DISPOSITION
  FROM RAW.HIS_ADT_HL7 WHERE MSG_TYPE = 'ADT^A03'),
j AS (
  SELECT a.*, d.DISCHARGED_AT, d.DISPOSITION,
         LEAD(a.ADMITTED_AT) OVER (PARTITION BY a.PATIENT_ID ORDER BY a.ADMITTED_AT) AS NEXT_ADMITTED_AT
  FROM adm a LEFT JOIN dis d USING (EPISODE_ID))
SELECT EPISODE_ID, PATIENT_ID, HOSPITAL_ID, SPECIALTY, DIAGNOSIS_CODE, DIAGNOSIS, ADMITTED_AT, DISCHARGED_AT, DISPOSITION,
       TO_DATE(ADMITTED_AT) AS ADMISSION_DATE, TO_DATE(DISCHARGED_AT) AS DISCHARGE_DATE,
       DISCHARGED_AT IS NULL AS IS_ACTIVE,
       ROUND(DATEDIFF(minute, ADMITTED_AT, COALESCE(DISCHARGED_AT, '2026-11-12 12:40:00'::TIMESTAMP_NTZ)) / 1440, 2) AS LOS_DAYS,
       HOUR(DISCHARGED_AT) < 12 AS DISCHARGED_BEFORE_NOON,
       DISCHARGED_AT IS NOT NULL AND NEXT_ADMITTED_AT IS NOT NULL AND DATEDIFF(day, DISCHARGED_AT, NEXT_ADMITTED_AT) <= 30 AS READMITTED_30D
FROM j;

-- Beds occupied at midnight, per hospital and day (occupancy = occupied / beds).
CREATE OR REPLACE DYNAMIC TABLE CORE.BED_OCCUPANCY_DAILY TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Beds occupied at midnight by hospital and day'
AS
SELECT c.CAL_DATE AS OCC_DATE, e.HOSPITAL_ID, COUNT(*) AS BEDS_OCCUPIED
FROM CORE.INPATIENT_EPISODE e
JOIN REF.CALENDAR c ON c.CAL_DATE > TO_DATE(e.ADMITTED_AT) AND c.CAL_DATE <= COALESCE(TO_DATE(e.DISCHARGED_AT), '2026-11-12'::DATE)
WHERE c.CAL_DATE BETWEEN '2025-12-01' AND '2026-11-12'
GROUP BY 1, 2;

-- ---------- Bloco operatório ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.SURGERY TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Surgeries with delays, overrun versus estimate and cancellations'
AS
SELECT CASE_ID, HOSPITAL_ID, ROOM_ID, SPECIALTY, PROCEDURE_NAME, SURGEON, PATIENT_ID, PAYER_ID, ASA, AGE, SURGERY_DATE,
       PLANNED_START, ACTUAL_START, SURGEON_ESTIMATE_MIN, ACTUAL_DURATION_MIN, TURNOVER_MIN, IS_ROBOTIC,
       CANCELLED_SAME_DAY, CANCEL_REASON, ICU_AFTER,
       DATEDIFF(minute, PLANNED_START, ACTUAL_START) AS START_DELAY_MIN,
       HOUR(PLANNED_START) = 8 AND MINUTE(PLANNED_START) = 0 AS IS_FIRST_CASE,
       ACTUAL_DURATION_MIN - SURGEON_ESTIMATE_MIN AS OVERRUN_MIN
FROM RAW.HIS_SURGERY_LOG;

-- ---------- Consultas ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.APPOINTMENT TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Outpatient appointments (hospitals and clinics), including the next 7 days'
AS
SELECT a.APPOINTMENT_ID, a.UNIT_ID, a.UNIT_TYPE, COALESCE(h.SHORT_NAME, c.SHORT_NAME) AS UNIT_NAME, COALESCE(h.REGION, c.REGION) AS REGION,
       a.SPECIALTY, a.PATIENT_ID, a.PAYER_ID, a.BOOKED_AT, a.APPOINTMENT_TS, TO_DATE(a.APPOINTMENT_TS) AS APPOINTMENT_DATE, HOUR(a.APPOINTMENT_TS) AS APPOINTMENT_HOUR,
       DATEDIFF(day, a.BOOKED_AT, a.APPOINTMENT_TS) AS LEAD_DAYS, a.BOOKING_CHANNEL, a.IS_TELECONSULT, a.IS_FIRST_VISIT, a.CONFIRMED_IN_APP,
       a.DISTANCE_KM, a.RAIN_FORECAST, a.STATUS, a.STATUS = 'Falta' AS NO_SHOW
FROM RAW.HIS_APPOINTMENTS a
LEFT JOIN REF.HOSPITALS h ON h.HOSPITAL_ID = a.UNIT_ID
LEFT JOIN REF.CLINICS c ON c.CLINIC_ID = a.UNIT_ID;

-- ---------- Faturação ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.INVOICE TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Invoices with payer, status, days to payment and the payer response text'
AS
SELECT i.INVOICE_ID, i.EPISODE_ID, i.EPISODE_TYPE, i.HOSPITAL_ID, i.PATIENT_ID, i.PAYER_ID, p.SHORT_NAME AS PAYER, p.PAYER_TYPE, i.SPECIALTY,
       i.SERVICE_DATE, i.INVOICE_DATE, i.AMOUNT_EUR, i.NEEDS_PRIOR_AUTH, i.HAS_PRIOR_AUTH, i.IS_IMAGING, i.STATUS,
       i.STATUS = 'Rejeitada' AS IS_REJECTED, i.PAID_DATE, DATEDIFF(day, i.INVOICE_DATE, i.PAID_DATE) AS DAYS_TO_PAY,
       r.RESPONSE_TEXT, r.RECEIVED_AT AS RESPONSE_AT
FROM RAW.BILLING_INVOICES i
JOIN REF.PAYERS p ON p.PAYER_ID = i.PAYER_ID
LEFT JOIN RAW.PAYER_RESPONSES r ON r.INVOICE_ID = i.INVOICE_ID;

-- ---------- Daily hospital KPIs (the grain of the operations views) ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.HOSPITAL_DAY_KPI TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'One row per hospital and day: ER, admissions, discharges, occupancy, surgeries'
AS
WITH er AS (SELECT HOSPITAL_ID, ARRIVAL_DATE d, COUNT(*) er_visits, AVG(WAIT_FIRST_PHYSICIAN_MIN) er_wait, COUNT_IF(REASON_GROUP = 'Respiratória') er_resp FROM CORE.ER_EPISODE GROUP BY 1, 2),
ad AS (SELECT HOSPITAL_ID, ADMISSION_DATE d, COUNT(*) admissions FROM CORE.INPATIENT_EPISODE GROUP BY 1, 2),
di AS (SELECT HOSPITAL_ID, DISCHARGE_DATE d, COUNT(*) discharges, COUNT_IF(DISCHARGED_BEFORE_NOON) discharges_noon FROM CORE.INPATIENT_EPISODE WHERE DISCHARGE_DATE IS NOT NULL GROUP BY 1, 2),
sx AS (SELECT HOSPITAL_ID, SURGERY_DATE d, COUNT_IF(NOT CANCELLED_SAME_DAY) surgeries, COUNT_IF(CANCELLED_SAME_DAY) surgeries_cancelled, SUM(IFF(CANCELLED_SAME_DAY, 0, ACTUAL_DURATION_MIN)) surgery_minutes FROM CORE.SURGERY GROUP BY 1, 2)
SELECT h.HOSPITAL_ID, h.SHORT_NAME AS HOSPITAL, h.REGION, h.BEDS, c.CAL_DATE AS KPI_DATE,
       COALESCE(er.er_visits, 0) AS ER_VISITS, er.er_wait AS ER_WAIT_AVG_MIN, COALESCE(er.er_resp, 0) AS ER_RESPIRATORY,
       COALESCE(ad.admissions, 0) AS ADMISSIONS, COALESCE(di.discharges, 0) AS DISCHARGES, COALESCE(di.discharges_noon, 0) AS DISCHARGES_BEFORE_NOON,
       COALESCE(o.BEDS_OCCUPIED, 0) AS BEDS_OCCUPIED, ROUND(100 * COALESCE(o.BEDS_OCCUPIED, 0) / h.BEDS, 2) AS OCCUPANCY_PCT,
       COALESCE(sx.surgeries, 0) AS SURGERIES, COALESCE(sx.surgeries_cancelled, 0) AS SURGERIES_CANCELLED, COALESCE(sx.surgery_minutes, 0) AS SURGERY_MINUTES
FROM REF.HOSPITALS h
JOIN REF.CALENDAR c ON c.CAL_DATE BETWEEN '2025-12-01' AND '2026-11-11'
LEFT JOIN er ON er.HOSPITAL_ID = h.HOSPITAL_ID AND er.d = c.CAL_DATE
LEFT JOIN ad ON ad.HOSPITAL_ID = h.HOSPITAL_ID AND ad.d = c.CAL_DATE
LEFT JOIN di ON di.HOSPITAL_ID = h.HOSPITAL_ID AND di.d = c.CAL_DATE
LEFT JOIN sx ON sx.HOSPITAL_ID = h.HOSPITAL_ID AND sx.d = c.CAL_DATE
LEFT JOIN CORE.BED_OCCUPANCY_DAILY o ON o.HOSPITAL_ID = h.HOSPITAL_ID AND o.OCC_DATE = c.CAL_DATE;

-- ---------- Pharmacy stock coverage ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.STOCK_COVERAGE TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Latest stock per hospital and material, with days of cover and value expiring in 60 days'
AS
WITH last AS (SELECT * FROM RAW.SAP_STOCK_DAILY QUALIFY ROW_NUMBER() OVER (PARTITION BY HOSPITAL_ID, MATERIAL_ID ORDER BY STOCK_DATE DESC) = 1),
avg28 AS (SELECT HOSPITAL_ID, MATERIAL_ID, AVG(CONSUMED_UNITS) avg_daily FROM RAW.SAP_STOCK_DAILY WHERE STOCK_DATE >= '2026-10-15' GROUP BY 1, 2)
SELECT l.HOSPITAL_ID, l.MATERIAL_ID, l.MATERIAL_NAME, l.CATEGORY, l.STOCK_DATE, l.STOCK_UNITS, l.SAFETY_STOCK, a.avg_daily AS AVG_DAILY_CONSUMPTION,
       ROUND(l.STOCK_UNITS / NULLIF(a.avg_daily, 0), 1) AS DAYS_OF_COVER, l.UNIT_COST_EUR,
       ROUND(l.STOCK_UNITS * l.UNIT_COST_EUR, 2) AS STOCK_VALUE_EUR,
       IFF(l.EXPIRY_DATE <= DATEADD(day, 60, l.STOCK_DATE), ROUND(l.STOCK_UNITS * l.UNIT_COST_EUR, 2), 0) AS VALUE_EXPIRING_60D_EUR
FROM last l JOIN avg28 a USING (HOSPITAL_ID, MATERIAL_ID);

-- ---------- Workforce load (rosters, overtime, nights, rest) ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.EMPLOYEE_WORKLOAD TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Workload per employee over the last 4 weeks and nights in the last 14 days'
AS
SELECT s.EMPLOYEE_ID,
       SUM(IFF(s.SHIFT_DATE >= '2026-10-15', s.HOURS, 0)) AS HOURS_4W,
       SUM(IFF(s.SHIFT_DATE >= '2026-10-15' AND s.IS_OVERTIME, s.HOURS - 8, 0)) AS OVERTIME_HOURS_4W,
       COUNT_IF(s.SHIFT_DATE >= '2026-10-29' AND s.SHIFT_TYPE = 'Noite') AS NIGHTS_14D,
       COUNT_IF(s.SHIFT_DATE >= '2026-10-15' AND s.REST_HOURS_BEFORE < 11) AS SHORT_RESTS_4W
FROM RAW.UKG_SHIFTS s GROUP BY 1;

-- ---------- Colaborador 360° ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.EMPLOYEE_360 TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Employee 360: HR record, workload, risks and (for profiled staff) the portal profile'
AS
SELECT e.*, h.SHORT_NAME AS HOSPITAL, w.HOURS_4W, w.OVERTIME_HOURS_4W, w.NIGHTS_14D, w.SHORT_RESTS_4W,
       p.RISKS AS PROFILE_RISKS, p.INSIGHTS AS PROFILE_INSIGHTS, p.NEXT_BEST_ACTIONS AS PROFILE_NEXT_BEST_ACTIONS, p.TRAINING AS PROFILE_TRAINING
FROM CORE.DIM_EMPLOYEE e
LEFT JOIN REF.HOSPITALS h ON h.HOSPITAL_ID = e.HOSPITAL_ID
LEFT JOIN CORE.EMPLOYEE_WORKLOAD w ON w.EMPLOYEE_ID = e.EMPLOYEE_ID
LEFT JOIN REF.EMPLOYEE_PROFILES p ON p.PROFILE_ID = e.PROFILE_ID;

-- ---------- Doente 360° ----------
CREATE OR REPLACE DYNAMIC TABLE CORE.PATIENT_360 TARGET_LAG = '1 hour' WAREHOUSE = LUZ_TRANSFORM_WH
  COMMENT = 'Patient 360: demographics, utilisation and spend in 12 months, latest HbA1c, app use, profile'
AS
WITH er AS (SELECT PATIENT_ID, COUNT(*) er_12m, MAX(ARRIVED_AT) last_er FROM CORE.ER_EPISODE GROUP BY 1),
ip AS (SELECT PATIENT_ID, COUNT(*) admissions_12m, COUNT_IF(READMITTED_30D) readmissions_12m, MAX(ADMITTED_AT) last_admission FROM CORE.INPATIENT_EPISODE GROUP BY 1),
ap AS (SELECT PATIENT_ID, COUNT_IF(STATUS = 'Realizada') consults_12m, COUNT_IF(NO_SHOW) no_shows_12m, MIN(IFF(STATUS = 'Marcada', APPOINTMENT_TS, NULL)) next_appointment FROM CORE.APPOINTMENT GROUP BY 1),
inv AS (SELECT PATIENT_ID, SUM(AMOUNT_EUR) spend_12m FROM CORE.INVOICE GROUP BY 1),
lab AS (SELECT PATIENT_ID, VALUE_NUM hba1c, COLLECTED_AT hba1c_at FROM RAW.LIS_RESULTS WHERE LOINC_CODE = '4548-4' QUALIFY ROW_NUMBER() OVER (PARTITION BY PATIENT_ID ORDER BY COLLECTED_AT DESC) = 1),
app AS (SELECT PATIENT_ID, COUNT(*) app_events_30d FROM RAW.MYLUZ_EVENTS GROUP BY 1)
SELECT d.*, COALESCE(er.er_12m, 0) AS ER_VISITS_12M, COALESCE(ip.admissions_12m, 0) AS ADMISSIONS_12M, COALESCE(ip.readmissions_12m, 0) AS READMISSIONS_12M,
       COALESCE(ap.consults_12m, 0) AS CONSULTS_12M, COALESCE(ap.no_shows_12m, 0) AS NO_SHOWS_12M, ap.next_appointment AS NEXT_APPOINTMENT,
       ROUND(COALESCE(inv.spend_12m, 0), 2) AS SPEND_12M_EUR, lab.hba1c AS LAST_HBA1C, lab.hba1c_at AS LAST_HBA1C_AT,
       COALESCE(app.app_events_30d, 0) AS APP_EVENTS_30D, GREATEST_IGNORE_NULLS(er.last_er, ip.last_admission) AS LAST_HOSPITAL_CONTACT,
       pr.RISKS AS PROFILE_RISKS, pr.PROBLEMS AS PROFILE_PROBLEMS, pr.MEDICATIONS AS PROFILE_MEDICATIONS, pr.CARE_GAPS AS PROFILE_CARE_GAPS,
       pr.NEXT_BEST_ACTIONS AS PROFILE_NEXT_BEST_ACTIONS, pr.SUMMARY AS PROFILE_SUMMARY
FROM CORE.DIM_PATIENT d
LEFT JOIN er ON er.PATIENT_ID = d.PATIENT_ID
LEFT JOIN ip ON ip.PATIENT_ID = d.PATIENT_ID
LEFT JOIN ap ON ap.PATIENT_ID = d.PATIENT_ID
LEFT JOIN inv ON inv.PATIENT_ID = d.PATIENT_ID
LEFT JOIN lab ON lab.PATIENT_ID = d.PATIENT_ID
LEFT JOIN app ON app.PATIENT_ID = d.PATIENT_ID
LEFT JOIN REF.PATIENT_PROFILES pr ON pr.PROFILE_ID = d.PROFILE_ID;
